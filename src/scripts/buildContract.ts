type Operation = {
  tags?: string[];
  summary?: string;
  description?: string;
  'x-auth'?: string;
  requestBody?: {content: {'application/json': {schema: {$ref?: string}}}};
  responses: Record<
    string,
    {description: string; content?: {'application/json': {schema: {$ref?: string}}}}
  >;
};

const doc = generateOpenApiDocument() as unknown as {
  paths: Record<string, Record<string, Operation>>;
};
const examples = JSON.parse(
  await readFile('docs/examples.json', 'utf8').catch(() => '{}'),
) as Record<string, unknown>;

const AUTH_LABEL: Record<string, string> = {
  public: 'public',
  user: 'any user',
  coach: 'coach',
  client: 'client',
};
const json = (value: unknown) => `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``;
const example = (key: string, title: string) =>
  examples[key] ? `**${title}**\n\n${json(examples[key])}\n` : '';

function endpointTables() {
  const byTag = new Map<string, string[]>();
  for (const [path, methods] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      const tag = op.tags?.[0] ?? 'Other';
      const success = Object.keys(op.responses).find(code => code.startsWith('2')) ?? '';
      const errors = Object.entries(op.responses)
        .filter(([code]) => !code.startsWith('2'))
        .flatMap(([, r]) => r.description.split(', '))
        .filter(code => !['VALIDATION_ERROR', 'UNAUTHORIZED', 'TOKEN_EXPIRED'].includes(code));
      const row = `| \`${method.toUpperCase()}\` | \`${path.replace('/api/v1', '')}\` | ${AUTH_LABEL[op['x-auth'] ?? 'public']} | ${op.summary ?? ''} | ${success} | ${errors.map(e => `\`${e}\``).join(' ')} |`;
      byTag.set(tag, [...(byTag.get(tag) ?? []), row]);
    }
  }
  return [...byTag.entries()]
    .map(
      ([tag, rows]) =>
        `### ${tag}\n\n| Method | Path | Who | What | OK | Errors (besides validation/auth) |\n| --- | --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`,
    )
    .join('\n');
}

